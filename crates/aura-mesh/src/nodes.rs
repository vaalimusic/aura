//! Explicit, identity-pinned community nodes. Never trust an address from a stranger.
use crate::{Multiaddr, Result};
use libp2p::multiaddr::Protocol;

pub const DEFAULT_ADDRESSES: [&str; 2] = [
    crate::audio::DEFAULT_RELAY,
    "/dns4/aura2.ltwo.ru/tcp/45071/p2p/12D3KooWB3V4copXp6jDuEN8Z1VQg8tnXVMst5uAszKBxfin9vbY",
];

const GENERATED_HEADER: &str = "# Aura Nodes: one pinned multiaddr per line; up to four nodes.\n";

fn default_text() -> String {
    format!("{GENERATED_HEADER}{}\n", DEFAULT_ADDRESSES.join("\n"))
}

fn write_defaults(path: &std::path::Path, replace: bool) -> Result<()> {
    use std::io::Write;
    let mut temp = tempfile::NamedTempFile::new_in(path.parent().ok_or("No profile directory")?)?;
    temp.write_all(default_text().as_bytes())?;
    temp.as_file().sync_all()?;
    if replace {
        temp.persist(path)?;
    } else {
        temp.persist_noclobber(path)?;
    }
    Ok(())
}

#[derive(Clone, Debug)]
pub struct Nodes(Vec<Multiaddr>);
impl Nodes {
    pub fn new(addresses: Vec<Multiaddr>) -> Result<Self> {
        let mut nodes = Vec::new();
        for address in addresses {
            let parts: Vec<_> = address.iter().collect();
            if !matches!(
                &parts[..],
                [
                    Protocol::Ip4(_) | Protocol::Ip6(_) | Protocol::Dns4(_) | Protocol::Dns6(_),
                    Protocol::Tcp(1..),
                    Protocol::P2p(_)
                ]
            ) {
                return Err(
                    "Адрес Aura Node должен содержать TCP-порт и закреплённый PeerId.".into(),
                );
            }
            if !nodes.contains(&address) {
                if nodes
                    .iter()
                    .any(|node: &Multiaddr| node.iter().last() == address.iter().last())
                {
                    return Err("У каждого резервного узла должен быть собственный PeerId.".into());
                }
                nodes.push(address);
            }
        }
        if nodes.is_empty() || nodes.len() > 4 {
            return Err("Нужно указать от 1 до 4 Aura Nodes.".into());
        }
        Ok(Self(nodes))
    }
    pub fn parse(text: &str) -> Result<Self> {
        if text.len() > 8192 {
            return Err("Список Aura Nodes слишком большой.".into());
        }
        Self::new(
            text.split(['\n', '\r'])
                .map(str::trim)
                .filter(|line| !line.is_empty() && !line.starts_with('#'))
                .flat_map(|line| line.split(';'))
                .map(str::trim)
                .filter(|address| !address.is_empty())
                .map(str::parse)
                .collect::<std::result::Result<Vec<_>, _>>()?,
        )
    }
    pub fn addresses(&self) -> &[Multiaddr] {
        &self.0
    }
    pub fn from_profile(profile: &std::path::Path) -> Result<Self> {
        if let Ok(text) = std::env::var("AURA_RELAYS") {
            return Self::parse(&text);
        }
        if let Ok(text) = std::env::var("AURA_RELAY") {
            return Self::parse(&text);
        }
        Self::from_file(&profile.join("nodes.txt"))
    }
    fn from_file(path: &std::path::Path) -> Result<Self> {
        match std::fs::File::open(path) {
            Ok(file) => {
                let mut text = String::new();
                std::io::Read::read_to_string(&mut std::io::Read::take(file, 8193), &mut text)?;
                // Migrate only the exact file generated by the previous version.
                // Custom lists, including custom single-node configurations, stay intact.
                let legacy = format!("{GENERATED_HEADER}{}\n", crate::audio::DEFAULT_RELAY);
                if text.replace("\r\n", "\n") == legacy {
                    let nodes = Self::parse(&default_text())?;
                    write_defaults(path, true)?;
                    return Ok(nodes);
                }
                Self::parse(&text)
            }
            Err(error) if error.kind() == std::io::ErrorKind::NotFound => {
                let nodes = Self::parse(&default_text())?;
                write_defaults(path, false)?;
                Ok(nodes)
            }
            Err(error) => Err(error.into()),
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn validates_bounded_pinned_addresses_and_legacy_default() {
        let address = crate::audio::DEFAULT_RELAY;
        assert_eq!(
            Nodes::parse(&format!(
                "# Nodes; comment, not an address\n{address};{address}"
            ))
            .unwrap()
            .addresses()
            .len(),
            1
        );
        assert!(Nodes::parse("/dns4/example.org/tcp/45071").is_err());
        assert!(Nodes::parse("").is_err());
        assert!(Nodes::parse(&"x".repeat(8193)).is_err());
    }
    #[test]
    fn generated_profiles_upgrade_but_custom_node_lists_remain_unchanged() {
        // Exercise the file behavior without depending on process-global environment overrides.
        let dir = tempfile::tempdir().unwrap();
        let path = dir.path().join("nodes.txt");
        assert_eq!(Nodes::from_file(&path).unwrap().addresses().len(), 2);
        std::fs::write(
            &path,
            format!("{GENERATED_HEADER}{}\n", crate::audio::DEFAULT_RELAY),
        )
        .unwrap();
        assert_eq!(Nodes::from_file(&path).unwrap().addresses().len(), 2);
        assert_eq!(
            Nodes::parse(&std::fs::read_to_string(&path).unwrap())
                .unwrap()
                .addresses()
                .len(),
            2
        );
        std::fs::write(
            &path,
            format!("# My custom list\n{}\n", crate::audio::DEFAULT_RELAY),
        )
        .unwrap();
        let before = std::fs::read(&path).unwrap();
        assert_eq!(Nodes::from_file(&path).unwrap().addresses().len(), 1);
        assert_eq!(std::fs::read(&path).unwrap(), before);
    }
}
